"""Generate src/wsock32.def from the system's 32-bit wsock32.dll.

Exports that the system DLL forwards (to ws2_32/mswsock) are forwarded the same
way; the few it implements itself are routed to thunks in proxy.cpp that call
the real System32 wsock32.dll.
"""
import os

import pefile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SYS = os.path.join(os.environ.get("WINDIR", r"C:\Windows"), "SysWOW64", "wsock32.dll")
# stdcall argument bytes of the non-forwarded exports (see proxy.cpp)
THUNK_ARGS = {"getsockopt": 20, "recv": 16, "recvfrom": 24, "setsockopt": 20}

pe = pefile.PE(SYS)
lines = ["; Generated by tools/gen_def.py - do not edit", "LIBRARY wsock32", "EXPORTS"]
for e in sorted(pe.DIRECTORY_ENTRY_EXPORT.symbols, key=lambda e: e.ordinal):
    name = e.name.decode()
    if e.forwarder:
        lines.append(f"  {name} = {e.forwarder.decode()} @{e.ordinal}")
    else:
        lines.append(f"  {name} = proxy_{name}@{THUNK_ARGS[name]} @{e.ordinal}")
with open(os.path.join(ROOT, "src", "wsock32.def"), "w") as f:
    f.write("\n".join(lines) + "\n")
print(f"{len(lines) - 3} exports")
